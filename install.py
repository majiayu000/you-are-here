#!/usr/bin/env python3
"""Install you-are-here for Claude Code, Codex and Grok.

  python3 install.py              skills only (symlinks)
  python3 install.py --all        skills + background subagents + automation rules
  python3 install.py --agents     subagent definitions only
  python3 install.py --rules      automation rules only
  python3 install.py --uninstall  remove everything this script installed
  add --dry-run to print the plan without touching anything

Where things go:
  skills  ~/.claude/skills, ~/.codex/skills, ~/.agents/skills   (symlink to this folder; Grok reads the last two)
  agents  ~/.claude/agents/you-are-here.md, ~/.codex/agents/you-are-here.toml, ~/.grok/agents/you-are-here.md
  rules   ~/.claude/rules/you-are-here.md   (Claude Code; Grok reads it via Claude compat)
          ~/.codex/AGENTS.md                (marked block, backed up before the first edit)
          ~/.grok/rules/you-are-here.md      (only when Grok's Claude-rules compat is off)
Files are only touched if they are ours: symlinks to this folder, or files carrying MARK.
"""
import argparse
import os
import re
import shutil
import sys
import time

SRC = os.path.dirname(os.path.realpath(__file__))
HOME = os.path.expanduser("~")
NAME = "you-are-here"
MARK = "generated by you-are-here/install.py"
BEGIN, END = "<!-- you-are-here:begin -->", "<!-- you-are-here:end -->"


def p(*parts):
    return os.path.join(HOME, *parts)


class Plan:
    def __init__(self, dry):
        self.dry = dry

    def say(self, verb, path, note=""):
        print(f"{'[dry-run] ' if self.dry else ''}{verb:9} {path}{'  ' + note if note else ''}")

    def link(self, dest):
        if os.path.islink(dest):
            if os.path.realpath(dest) == SRC:
                return self.say("ok", dest)
            return self.say("skip", dest, "symlink points elsewhere")
        if os.path.exists(dest):
            return self.say("skip", dest, "exists and is not our symlink")
        self.say("link", dest, f"-> {SRC}")
        if not self.dry:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            os.symlink(SRC, dest)

    def write(self, dest, text):
        if os.path.exists(dest) and MARK not in open(dest, encoding="utf-8").read():
            return self.say("skip", dest, "exists and was not written by this installer")
        if os.path.exists(dest) and open(dest, encoding="utf-8").read() == text:
            return self.say("ok", dest)
        self.say("write", dest)
        if not self.dry:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "w", encoding="utf-8") as f:
                f.write(text)

    def block(self, dest, text):
        """Insert or replace our marked block at the end of a shared file."""
        old = open(dest, encoding="utf-8").read() if os.path.exists(dest) else ""
        if not markers_ok(old):
            sys.exit(f"install: {dest} has unbalanced or repeated {BEGIN} / {END} markers; fix it by hand first")
        blk = f"{BEGIN}\n{text.rstrip()}\n{END}\n"
        if BEGIN in old:
            new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: blk, old, flags=re.S)
        else:
            new = old + ("\n" if old and not old.endswith("\n\n") else "") + blk
        if new == old:
            return self.say("ok", dest, "block up to date")
        self.say("update" if BEGIN in old else "append", dest, "marked block")
        if not self.dry:
            if old and BEGIN not in old:
                bak = f"{dest}.bak-you-are-here-{time.strftime('%Y%m%d-%H%M%S')}"
                shutil.copy2(dest, bak)
                self.say("backup", bak)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "w", encoding="utf-8") as f:
                f.write(new)

    def remove(self, dest):
        if os.path.islink(dest) and os.path.realpath(dest) == SRC:
            self.say("remove", dest)
            if not self.dry:
                os.remove(dest)
        elif os.path.isfile(dest) and not os.path.islink(dest) and MARK in open(dest, encoding="utf-8").read():
            self.say("remove", dest)
            if not self.dry:
                os.remove(dest)

    def unblock(self, dest):
        if not os.path.exists(dest):
            return
        old = open(dest, encoding="utf-8").read()
        if BEGIN not in old and END not in old:
            return
        if not markers_ok(old):
            sys.exit(f"install: {dest} has unbalanced or repeated {BEGIN} / {END} markers; fix it by hand first")
        new = re.sub(r"\n?" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "\n", old, flags=re.S)
        self.say("unblock", dest)
        if not self.dry:
            with open(dest, "w", encoding="utf-8") as f:
                f.write(new.rstrip("\n") + "\n")


def markers_ok(text):
    """Zero blocks, or exactly one BEGIN followed by one END."""
    b, e = text.count(BEGIN), text.count(END)
    return (b, e) == (0, 0) or ((b, e) == (1, 1) and text.index(BEGIN) < text.index(END))


def tmpl(name, skill_dir):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read().replace("{{SKILL_DIR}}", skill_dir)


def grok_reads_claude_rules():
    cfg = p(".grok", "config.toml")
    if os.environ.get("GROK_CLAUDE_RULES_ENABLED", "").lower() == "false":
        return False
    try:
        text = open(cfg, encoding="utf-8").read()
    except OSError:
        return True
    m = re.search(r"^\[compat\.claude\](.*?)(?=^\[|\Z)", text, flags=re.S | re.M)
    return not (m and re.search(r"^\s*rules\s*=\s*false", m.group(1), flags=re.M))


SKILL_LINKS = [p(".claude", "skills", NAME), p(".codex", "skills", NAME), p(".agents", "skills", NAME)]


def agent_files():
    # each agent points at the skill path it discovers, so the instructions match what it loads
    return [
        (p(".claude", "agents", f"{NAME}.md"), "agents/claude.md", p(".claude", "skills", NAME), "md"),
        (p(".codex", "agents", f"{NAME}.toml"), "agents/codex.toml", p(".codex", "skills", NAME), "toml"),
        (p(".grok", "agents", f"{NAME}.md"), "agents/grok.md", p(".agents", "skills", NAME), "md"),
    ]


def stamp(text, kind):
    return f"{text.rstrip()}\n\n<!-- {MARK} -->\n" if kind == "md" else f"# {MARK}\n{text}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--skills", action="store_true")
    ap.add_argument("--agents", action="store_true")
    ap.add_argument("--rules", action="store_true")
    ap.add_argument("--uninstall", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    pl = Plan(a.dry_run)

    if a.uninstall:
        for d in SKILL_LINKS:
            pl.remove(d)
        for dest, *_ in agent_files():
            pl.remove(dest)
        pl.remove(p(".claude", "rules", f"{NAME}.md"))
        pl.remove(p(".grok", "rules", f"{NAME}.md"))
        pl.unblock(p(".codex", "AGENTS.md"))
        return

    picked = a.skills or a.agents or a.rules
    skills, agents, rules = (True, True, True) if a.all else (a.skills or not picked, a.agents, a.rules)
    if skills or agents or rules:  # agents and rules reference the skill paths, so link them too
        for d in SKILL_LINKS:
            pl.link(d)
    if agents:
        for dest, src, skill_dir, kind in agent_files():
            pl.write(dest, stamp(tmpl(src, skill_dir), kind))
    if rules:
        rule = tmpl("rules/you-are-here.md", p(".claude", "skills", NAME))
        pl.write(p(".claude", "rules", f"{NAME}.md"), stamp(rule, "md"))
        pl.block(p(".codex", "AGENTS.md"), tmpl("rules/you-are-here.md", p(".codex", "skills", NAME)))
        if not grok_reads_claude_rules():
            pl.write(p(".grok", "rules", f"{NAME}.md"), stamp(tmpl("rules/you-are-here.md", p(".agents", "skills", NAME)), "md"))
        else:
            print(f"{'[dry-run] ' if pl.dry else ''}{'note':9} Grok reads ~/.claude/rules via Claude compat; no separate Grok rule needed")


if __name__ == "__main__":
    main()
